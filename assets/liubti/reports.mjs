export function typeReportHTML(profile, escapeHTML) {
  const report = Object.hasOwn(TYPE_REPORTS, profile?.code) ? TYPE_REPORTS[profile.code] : null;
  if (!report) return '';
  const section = (title, text) => `<section class="type-reading-section"><h3>${title}</h3><p>${escapeHTML(text)}</p></section>`;
  return `<article class="report-card type-reading" aria-labelledby="typeReadingTitle">
    <span class="eyebrow">认识你的推理风格</span><h2 id="typeReadingTitle">${escapeHTML(report.name)}的风格解读</h2>
    <p class="type-reading-note">以下是这一类型的通用画像，供你对照本局体验；上方四个维度展示本局问答依据。</p>
    ${section('推理画像', report.portrait)}
    <div class="type-reading-grid">${section('你的优势', report.strength)}${section('下一局建议', report.advice)}</div>
    <details class="type-reading-more"><summary>继续阅读盲点、提问示例与看山寄语</summary>
    ${section('容易卡住的地方', report.blindspot)}${section('提问方式示例', report.examples)}${section('看山寄语', report.message.replace(/^看山寄语：/, ''))}
    </details></article>`;
}
